type Dict = typeof dict.en;

function getNested(obj: any, path: string): string {
  const v = path.split(".").reduce((a, k) => (a ? a[k] : undefined), obj);
  if (typeof v === "string") return v;
  const parts = path.split(".");
  return parts[parts.length - 1];
}

const I18nContext = createContext<{
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: string) => string;
  dir: "ltr" | "rtl";
}>({ lang: "en", setLang: () => {}, t: (k) => k, dir: "ltr" });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const saved = localStorage.getItem("ssd_lang") as Lang | null;
    if (saved) return saved;
    const sys = navigator.language?.toLowerCase() ?? "en";
    return sys.startsWith("ar") ? "ar" : "en";
  });

  const setLang = (l: Lang) => {
    setLangState(l);
    localStorage.setItem("ssd_lang", l);
  };

  const dir: "ltr" | "rtl" = lang === "ar" ? "rtl" : "ltr";

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
  }, [lang, dir]);

  const value = useMemo(
    () => ({
      lang,
      setLang,
      dir,
      t: (k: string) => getNested(dict[lang] as Dict, k),
    }),
    [lang, dir]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
